#!/usr/bin/env python3
"""Generate crates/xerj-serve/src/decline_v2/{pytables,words}.rs from the frozen decline policy v2 (e2e1, 2026-10-31).

    python3 -I -B crates/xerj-serve/tools/gen_decline_tables.py DECLINE_V1_DIR OUT_DIR

pytables.rs = what Python's `re` and `str` read from their Unicode database (the frozen rows were scored with CPython 3.12):
\\w, \\d, \\s, case predicates, full lower / upper mappings, the IGNORECASE equivalence. words.rs = every word list of the frozen
rules.py and roles.py, read from the modules themselves so that no list is retyped. The Python files are the source: never edit
the generated files. Their sha256 go in the header; `decline_v2::FROZEN_SHA256` is checked against frozen_rules_v2.json by
the parity tools.
"""
import hashlib
import re
import sys
import unicodedata
from pathlib import Path
from re import _casefix
import _sre

sys.dont_write_bytecode = True
src, out = Path(sys.argv[1]), Path(sys.argv[2])
sys.path.insert(0, str(src))
import rules as R   # noqa: E402
import roles as RO  # noqa: E402


def ranges(pred):
    out_, a = [], None
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            ok = False
        else:
            ok = pred(c)
        if ok and a is None:
            a = c
        if not ok and a is not None:
            out_.append((a, c - 1))
            a = None
    if a is not None:
        out_.append((a, 0x10FFFF))
    return out_


def table(name, rs):
    body = ",".join(f"({a},{b})" for a, b in rs)
    return f"pub static {name}: &[(u32, u32)] = &[{body}];\n"


def chars():
    return (c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF)


W = re.compile(r"\w")
D = re.compile(r"\d")
S = re.compile(r"\s")
tabs = [("WORD", lambda c: W.match(chr(c)) is not None), ("DIGIT", lambda c: D.match(chr(c)) is not None),
        ("SPACE", lambda c: S.match(chr(c)) is not None), ("ALPHA", lambda c: chr(c).isalpha()),
        ("UPPER", lambda c: chr(c).isupper()), ("LOWER", lambda c: chr(c).islower()),
        # the two facts the final-sigma rule of str.lower() reads (probed through lower() itself: CPython exposes neither)
        ("CASED_NOT_IGNORABLE", lambda c: (chr(c) + "Σ").lower()[-1] == "ς"),
        ("CASE_IGNORABLE", lambda c: ("A" + chr(c) + "Σ").lower()[-1] == "ς" and (chr(c) + "Σ").lower()[-1] != "ς")]
o = [f"//! GENERATED by tools/gen_decline_tables.py: do not edit. CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n",
     "#![cfg_attr(rustfmt, rustfmt_skip)]\n"]
for n, p in tabs:
    o.append(table(n, ranges(p)))
for name, f in (("LOWER_MAP", str.lower), ("UPPER_MAP", str.upper)):
    rows = []
    for c in chars():
        m = f(chr(c))
        if m != chr(c):
            rows.append(f"({c},&[{','.join(str(ord(x)) for x in m)}])")
    o.append(f"pub static {name}: &[(u32, &[u32])] = &[{','.join(rows)}];\n")
# re.IGNORECASE: a character matches when the simple lower-case forms are equal or joined by re._casefix._EXTRA_CASES
canon = {}
for c in chars():
    lo = _sre.unicode_tolower(c)
    group = {lo} | set(_casefix._EXTRA_CASES.get(lo, ()))
    k = min(group)
    if k != c:
        canon[c] = k
o.append("pub static IGNORECASE_CANON: &[(u32, u32)] = &[" + ",".join(f"({k},{v})" for k, v in sorted(canon.items())) + "];\n")
out.joinpath("pytables.rs").write_text("".join(o), encoding="utf-8")


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def strs(name, xs):
    return f"pub static {name}: &[&str] = &[{','.join(rs(x) for x in sorted(xs))}];\n"


def ordered(name, xs):
    return f"pub static {name}: &[&[&str]] = &[{','.join('&[' + ','.join(rs(w) for w in p) + ']' for p in xs)}];\n"


def pairs(name, d):
    return f"pub static {name}: &[(&str, &str)] = &[{','.join(f'({rs(k)},{rs(v)})' for k, v in sorted(d.items()))}];\n"


sha = {n: hashlib.sha256((src / n).read_bytes()).hexdigest() for n in ("rules.py", "roles.py", "replay.py", "policy.py")}
sha["hybrid_bench_policy.py"] = hashlib.sha256((src.parent / "tools" / "hybrid_bench_policy.py").read_bytes()).hexdigest()
o = ["//! GENERATED by tools/gen_decline_tables.py from the frozen rules.py and roles.py: do not edit.\n",
     "#![cfg_attr(rustfmt, rustfmt_skip)]\n",
     "pub static FROZEN_SHA256: &[(&str, &str)] = &[" + ",".join(f"({rs(k)},{rs(v)})" for k, v in sha.items()) + "];\n"]
for n in ("AUX WH REQUEST_VERBS ACTION_VERBS FORMAT_OBJECTS CONDITIONAL LEADING_FILLERS DETERMINERS PREPOSITIONS RELATIVES VERB_STOPS "
          "UNITS SINGULAR_S IRREGULAR_PLURALS ID_WORDS DATE_HEADS PLACE_HEADS PLACE_FIELDS MEASURE_ADJ SUPERLATIVES EXTREMUM_WORDS "
          "AGG_WORDS ARITH_WORDS SET_WORDS COMPARATIVES COUNT_COMPARATIVES EQUALITY_CUES TIME_NOUNS ABBREV KEEP_CAPS MASKED").split():
    o.append(strs(n, getattr(R, n)))
o.append(ordered("GROUP_PHRASES", R.GROUP_PHRASES))
o.append(ordered("EXIST_PHRASES", R.EXIST_PHRASES))
o.append(pairs("PLACE_LEVEL", R.PLACE_LEVEL))
o.append(pairs("CUE_FAMILY", R.CUE_FAMILY))
o.append("pub static CUE_FIELD_STEMS: &[(&str, &[&str])] = &[" + ",".join(f"({rs(k)},&[{','.join(rs(s) for s in v)}])" for k, v in R.CUE_FIELD_STEMS.items()) + "];\n")
o.append(strs("GT_WORDS", RO.GT_WORDS))
o.append(strs("LT_WORDS", RO.LT_WORDS))
assert RO.AGE_WORDS == {"older": ("LT", "GT"), "newer": ("GT", None), "younger": ("GT", "LT")}
out.joinpath("words.rs").write_text("".join(o), encoding="utf-8")
print("ok", {k: v[:8] for k, v in sha.items()})
